      case ('qt')
        output_raw = output_scaled * output_std_qt_global + output_mean_qt_global
      case ('x_wind')
        output_raw = output_scaled * output_std_x_wind_global + output_mean_x_wind_global
      case ('y_wind')
        output_raw = output_scaled * output_std_y_wind_global + output_mean_y_wind_global
      case default
        error stop 'Unknown ENNUF scaling output variable'
      end select
    case default
      error stop 'Unknown ENNUF scaling domain'
    end select
  end subroutine ennuf_destandardise_output

end module gwd_ennuf_scaling_mod
