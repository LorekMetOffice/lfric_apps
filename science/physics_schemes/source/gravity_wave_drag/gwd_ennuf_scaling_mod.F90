  subroutine ennuf_standardise_input(input_raw, domain, input_scaled)
    real(real64), intent(in) :: input_raw(:)
    character(len=*), intent(in) :: domain
    real(real64), intent(out) :: input_scaled(:)

    if (size(input_raw) /= ennuf_n_input .or. size(input_scaled) /= ennuf_n_input) then
      error stop 'ENNUF input size mismatch: expected four channels plus six scalar features'
    end if
    select case (trim(domain))
    case ('us2')
      input_scaled = (input_raw - input_mean_us2) / input_std_us2
    case ('global')
      input_scaled = (input_raw - input_mean_global) / input_std_global
